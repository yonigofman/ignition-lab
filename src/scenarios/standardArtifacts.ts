import type { ScenarioArtifact } from "../engine/scenario";
import { buildSharedAuthArtifacts } from "./sharedArtifacts";

export interface StandardArtifactsOptions {
  cluster: string;
  baseDomain: string;
  computeReplicas: number;
  mastersSchedulable: boolean;
  clusterId: string;
  infraId: string;
  workerIgnitionNote: string;
}

/** The artifacts every UPI scenario produces before install starts (install-config → manifests → ignition-configs), parameterized by the handful of fields that actually differ between scenarios. */
export function buildStandardArtifacts(opts: StandardArtifactsOptions): ScenarioArtifact[] {
  const { cluster, baseDomain, computeReplicas, mastersSchedulable, clusterId, infraId, workerIgnitionNote } = opts;

  return [
    {
      id: "install-config",
      path: "install-config.yaml",
      language: "yaml",
      content: `apiVersion: v1
baseDomain: ${baseDomain}
metadata:
  name: ${cluster}
compute:
  - name: worker
    replicas: ${computeReplicas}
controlPlane:
  name: master
  replicas: 3
networking:
  networkType: OVNKubernetes
  machineNetwork:
    - cidr: 192.168.1.0/24
platform:
  none: {}
pullSecret: '{"auths": {"...": {}}}'
sshKey: |
  ssh-ed25519 AAAA... core@helper
`,
    },
    {
      id: "manifests",
      path: "manifests/cluster-scheduler-02-config.yml",
      language: "yaml",
      content: `apiVersion: config.openshift.io/v1
kind: Scheduler
metadata:
  name: cluster
spec:
  mastersSchedulable: ${mastersSchedulable}
  policy:
    name: ""
`,
      note: mastersSchedulable
        ? "Generated by `openshift-install create manifests`. This compact cluster has no dedicated workers (replicas: 0 above), so mastersSchedulable is turned on — the masters also run regular workloads."
        : "Generated by `openshift-install create manifests`. This cluster has dedicated workers (replicas > 0 above), so mastersSchedulable stays off — regular workloads run on the workers, not the control plane.",
    },
    {
      id: "bootstrap-ignition",
      path: "bootstrap.ign",
      language: "json",
      content: `{
  "ignition": { "version": "3.2.0" },
  "storage": {
    "files": ["/* ~1800 more lines: release image pull spec, bootkube unit files, etcd static pod manifests, CA bundles */"]
  },
  "systemd": {
    "units": [{ "name": "bootkube.service", "enabled": true }, { "name": "release-image.service", "enabled": true }]
  }
}
`,
      note: "Truncated. The real file is several MB — it embeds every static pod manifest, unit file, and CA bundle bootstrap needs to stand up the temporary control plane on its own.",
    },
    {
      id: "master-ignition",
      path: "master.ign",
      language: "json",
      content: `{
  "ignition": {
    "version": "3.2.0",
    "config": {
      "merge": [
        { "source": "https://api-int.${cluster}.${baseDomain}:22623/config/master" }
      ]
    }
  }
}
`,
      note: "A pointer config. The real machine config is fetched from this URL — bootstrap's Machine Config Server, reached through the API load balancer — not stored here.",
    },
    {
      id: "worker-ignition",
      path: "worker.ign",
      language: "json",
      content: `{
  "ignition": {
    "version": "3.2.0",
    "config": {
      "merge": [
        { "source": "https://api-int.${cluster}.${baseDomain}:22623/config/worker" }
      ]
    }
  }
}
`,
      note: workerIgnitionNote,
    },
    ...buildSharedAuthArtifacts({ cluster, baseDomain, clusterId, infraId }),
  ];
}
